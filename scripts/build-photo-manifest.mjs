/**
 * Generate `src/data/photoManifest.ts` from what is actually on disk.
 *
 * The slideshow renders from this manifest rather than probing the folder
 * blind, and `npm run check` re-runs it with --check so the manifest cannot
 * drift from the files — the same pattern as the attention inventory, for the
 * same reason: a surface that describes assets it does not have is lying.
 *
 * Kinds are assigned by filename shape, and titles only exist for the images
 * that arrived with names. The generated moments stay uncaptioned — inventing
 * captions for them would be set dressing.
 */
import sharp from 'sharp';
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const TITLES = {
  'twilight-stroll': 'campus twilight stroll',
  'bookstore-reading': 'the bookstore, late',
  'coffee-date': 'golden hour, two coffees',
  'study-picnic': 'the study picnic',
  'neon-downtown': 'downtown, texting nobody',
  'neon-tacos': 'tacos by the night street',
  'bridgeside': 'bridgeside',
  'stadium-night': 'the stadium, after',
  'contact-sheet': 'contact sheet',
  'moodboard': 'moodboard',
  'moodboard-2': 'moodboard, again',
  'photo-grid': 'the week in frames',
};

const rows = [];
for (const f of readdirSync('public/photos').filter((x) => x.endsWith('.webp')).sort()) {
  const slug = f.replace('.webp', '');
  const m = await sharp(join('public/photos', f)).metadata();
  const kind = slug.startsWith('room-')
    ? 'room'
    : /sheet|moodboard|grid/.test(slug)
      ? 'sheet'
      : 'moment';
  rows.push({
    src: `/photos/${f}`,
    w: m.width,
    h: m.height,
    kind,
    kb: Math.round(statSync(join('public/photos', f)).size / 1024),
    ...(TITLES[slug] ? { title: TITLES[slug] } : {}),
  });
}

// The reel runs moments, then the empty rooms as a quiet passage, then the
// sheets as fast beats. Order is the edit.
const order = { moment: 0, room: 1, sheet: 2 };
rows.sort((a, b) => order[a.kind] - order[b.kind] || a.src.localeCompare(b.src));

const out = `/**
 * GENERATED by \`scripts/build-photo-manifest.mjs\`. Do not edit by hand.
 * Regenerate with \`npm run photos\`; \`npm run check\` fails if this drifts
 * from the files actually in public/photos.
 */
export type Photo = {
  src: string;
  w: number;
  h: number;
  kind: 'moment' | 'room' | 'sheet';
  kb: number;
  title?: string;
};

export const PHOTOS: Photo[] = ${JSON.stringify(rows, null, 2)};
`;

if (process.argv.includes('--check')) {
  const current = readFileSync('src/data/photoManifest.ts', 'utf8');
  if (current.trim() !== out.trim()) {
    console.error('photo manifest is stale — run: npm run photos');
    process.exit(1);
  }
  console.log('photo manifest is current');
} else {
  writeFileSync('src/data/photoManifest.ts', out);
  console.log(`wrote src/data/photoManifest.ts — ${rows.length} photos`);
}
